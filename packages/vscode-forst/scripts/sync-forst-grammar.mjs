#!/usr/bin/env node
/**
 * Sync forst.tmLanguage.json to docs/languages/forst.json and build client-side highlighter.
 * Source of truth: packages/vscode-forst/syntaxes/forst.tmLanguage.json
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const source = path.join(
  repoRoot,
  "packages/vscode-forst/syntaxes/forst.tmLanguage.json"
);
const destGrammar = path.join(repoRoot, "docs/languages/forst.json");
const destHighlight = path.join(repoRoot, "docs/forst-highlight.js");
const tokenizePath = path.join(__dirname, "forst-tokenize.mjs");
const detectPath = path.join(__dirname, "forst-highlight-detect.mjs");
const browserPath = path.join(__dirname, "forst-highlight-browser.mjs");

const grammar = JSON.parse(fs.readFileSync(source, "utf8"));
const docsGrammar = {
  ...grammar,
  name: "ft",
  fileTypes: ["ft"],
};
fs.writeFileSync(destGrammar, JSON.stringify(docsGrammar, null, 2) + "\n");

function stripModuleExports(source) {
  return source
    .replace(/^\/\*\*[\s\S]*?\*\/\s*/m, "")
    .replace(/^export function /gm, "function ")
    .replace(/^export /gm, "")
    .trim();
}

const bundledTokenize = stripModuleExports(fs.readFileSync(tokenizePath, "utf8"));
const bundledDetect = stripModuleExports(fs.readFileSync(detectPath, "utf8"));
const browserSource = fs.readFileSync(browserPath, "utf8")
  .replace(/^\/\*\*[\s\S]*?\*\/\s*/m, "")
  .replace(/^\/\* global[\s\S]*?\*\/\s*/m, "")
  .trim();

const grammarLiteral = JSON.stringify(docsGrammar);

const bundled = `/* generated by sync-forst-grammar.mjs — do not edit */
(function () {
  "use strict";
  ${bundledTokenize}

  ${bundledDetect}

  const GRAMMAR = ${grammarLiteral};

  ${browserSource}
})();
`;

fs.writeFileSync(destHighlight, bundled);
console.log(`synced ${path.relative(repoRoot, source)} -> ${path.relative(repoRoot, destGrammar)}`);
console.log(`built ${path.relative(repoRoot, destHighlight)}`);
